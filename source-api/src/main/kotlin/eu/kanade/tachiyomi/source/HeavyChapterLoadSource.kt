package eu.kanade.tachiyomi.source

/**
 * SY --> 标记：该源「加载一个章节」的代价 = 取回一个可能很大的**整本文件**。
 *
 * 本 fork 里命中此标记的是 WebDAV 云盘源与「本地图源（本地文件夹）」：PDF / epub / rar / 7z
 * 这类无法按页流式取的格式，只能整本下载/拷贝到缓存后再读（实测单卷 220–370MB）。
 *
 * 为什么需要这个标记：
 *  阅读器会在「还差几页到章节末尾」「相邻章节的转场页」等时机**投机预载**相邻章节
 *  （见 `ReaderViewModel.preload`）。对 HttpSource 这类源，预载只是取页面列表 + 少量几张图，
 *  很便宜；但对本标记的源，预载 = 再把一整本文件下下来 —— 也就是「打开一卷实际下两卷」：
 *  双倍流量、双倍磁盘，而且**抢走用户当前正在等的那一卷的带宽**，首屏反而更慢。
 *
 * 行为契约：
 *  - 命中此标记的源，阅读器**跳过投机预载**（`preload`）。
 *  - 用户真正切到相邻章节时（`loadAdjacent`：工具栏上/下一章、点按翻章）**仍会正常加载**，
 *    只是不再提前下载。所以「章节切换时要等一下」是有意为之的取舍。
 * SY <--
 */
